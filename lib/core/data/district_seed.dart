  final int province;
  final double lat;
  final double lng;
  final String description;
  final List<Experience> types;
  final List<Season> seasons;
  final int cost;
  final String transport;
  final String safety;
  final List<SeedFestival> festivals;
  final List<String> foods;
  final bool lessExplored;
  final List<SeedPlace> places;

  const SeedDistrict(
    this.id,
    this.name,
    this.svgLabel,
    this.province,
    this.lat,
    this.lng,
    this.description,
    this.types,
    this.seasons,
    this.cost,
    this.transport,
    this.safety,
    this.festivals,
    this.foods,
    this.lessExplored,
    this.places,
  );
}

