// then edit every field. Cost levels: 1 = budget, 2 = moderate, 3 = premium.
// Coordinates are approximate district centres, used only for the
// near/medium/far distance filter (US-6.3).

import '../models/experience.dart';

class SeedPlace {
  final String name;
  final Experience type;
  final String description;
  const SeedPlace(this.name, this.type, this.description);
}

class SeedFestival {
  final String name;
  final String month;
  const SeedFestival(this.name, this.month);
}

class SeedDistrict {
